# The ledger data


def load(name: str) -> dict:
    with (LEDGER / name).open("rb") as handle:
        return tomllib.load(handle)


@dataclasses.dataclass
class Requirement:
    key: str
    native: str
    library: str
    python: list[str]
    bound: bool
    # Why no Python name can stand for this surface, when none can.
    no_python_spelling: str | None = None


@dataclasses.dataclass
class Sketch:
    name: str
    collection: str
    needs: str | None
    requires: list[Requirement]
    study: tuple[str, str] | None = None  # (relation, study stem)

    @property
    def unbound(self) -> list[Requirement]:
        return [requirement for requirement in self.requires if not requirement.bound]

    @property
    def bound(self) -> bool:
        return self.needs is not None and not self.unbound


@dataclasses.dataclass
class Study:
    stem: str
    combines: str | None
    relation: str | None
    native: str | None


class Ledger:
    """The ledger's data joined to the tree and judged against the extension."""

    def __init__(self, extension: Extension, sketch_root: pathlib.Path) -> None:
        self.extension = extension
        self.requirements = self._requirements(load("requirements.toml"))
        sketch_data = load("sketches.toml")
        registered = registrations(sketch_root)
        self.collections = self._collection_order(sketch_data, registered)
        self.studies = self._studies(
            load("studies.toml"), studies(sketch_root), registered
        )
        self.sketches = self._sketches(sketch_data, registered)
        self.coverage = load("coverage.toml")

    def _requirements(self, data: dict) -> dict[str, Requirement]:
        found = {}
        for key, record in data.get("requirement", {}).items():
            python = list(record.get("python", []))
            reason = record.get("no_python_spelling")
            if bool(python) == bool(reason):
                raise LedgerError(
                    f"typing/ledger/requirements.toml: `{key}` must give either "
                    "the Python spellings that stand for it in `python`, or why "
                    "none can in `no_python_spelling`, and not both"
                )
            bound = bool(python) and self.extension.all_resolve(python)
            found[key] = Requirement(
                key, record["native"], record["library"], python, bound, reason
            )
        return found

    @staticmethod
    def _collection_order(data: dict, registered: dict[str, Registration]) -> list[str]:
        order = list(data.get("collections", []))
        rest = sorted({entry.collection for entry in registered.values()} - set(order))
        present = {entry.collection for entry in registered.values()}
        return [collection for collection in order + rest if collection in present]

    @staticmethod
    def _studies(
        data: dict, stems: list[str], registered: dict[str, Registration]
    ) -> list[Study]:
        records = data.get("study", {})
        for stem in records:
            if stem not in stems:
                raise LedgerError(
                    f"typing/ledger/studies.toml describes {stem}, and no "
                    f"{stem}.py ships under src/sketch/sketches"
                )
        found = []
        for stem in stems:
            record = records.get(stem, {})
            relation = native = None
            if "ports" in record:
                relation, native = "Port", record["ports"]
            elif "adapts" in record:
                relation, native = "Adaptation", record["adapts"]
            if native is not None and native not in registered:
                raise LedgerError(
                    f"{stem} names {native}, which no C++ sketch registers"
                )
            found.append(Study(stem, record.get("combines"), relation, native))
        return found

    def _sketches(
        self, data: dict, registered: dict[str, Registration]
    ) -> list[Sketch]:
        records = data.get("sketch", {})
        for name in records:
            if name not in registered:
                raise LedgerError(
                    f"typing/ledger/sketches.toml describes `{name}`, which no "
                    "C++ sketch registers"
                )
        by_native = {study.native: study for study in self.studies if study.native}
        found = []
        for name, entry in registered.items():
            record = records.get(name)
            requires = []
            for key in record.get("requires", []) if record else []:
                if key not in self.requirements:
                    raise LedgerError(
                        f"`{name}` requires `{key}`, which typing/ledger/"
                        "requirements.toml does not record"
                    )
                requires.append(self.requirements[key])
            study = by_native.get(name)
            found.append(
                Sketch(
                    name,
                    entry.collection,
                    record["needs"] if record else None,
                    requires,
                    (study.relation, study.stem) if study and study.relation else None,
                )
            )
        return sorted(found, key=lambda sketch: sketch.name.casefold())

    def in_collection(self, collection: str) -> list[Sketch]:
        return [sketch for sketch in self.sketches if sketch.collection == collection]


