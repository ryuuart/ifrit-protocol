"""Generate PARITY.md, the Python ledger, from the built extension.

Run with the interpreter that matches the extension and PYTHONPATH pointing
to build/python, like generate.py. Three sources meet here and nothing else
is read:

- the extension, imported through the package's own modules in this
  checkout: whether a surface is bound is whether its Python spellings
  resolve there, and which public modules export nothing yet comes from
  walking typing/surface.py's table;
- the sketch registrations under src/sketch/sketches: which C++ sketches
  exist, the collection each files under, and which Python studies ship;
- typing/ledger: what each sketch needs, which Python spellings stand for
  each native surface, what each study combines, and what each library
  row claims.

Everything else in PARITY.md is prose an author wrote. It sits between
`<!-- prose: NAME -->` and `<!-- /prose -->` markers, and this pass carries
it over verbatim from the file already on disk. A prose block holds no
table: every table in the ledger is generated, so a row written by hand
inside a block stops the pass rather than riding along unjudged.

`--check` writes nothing and exits non-zero at the first line the checked-in
ledger does not agree with.

The ledger describes an extension built with every licensed SDK. One built
without them cannot judge it, so this exits with SKIPPED, which the drift
test reports as skipped and the `generate` target as a failure: in neither
mode is PARITY.md read or written.
"""

