# Rendering


def cell(text: str) -> str:
    """Text a table cell can hold: an unescaped pipe would end the cell."""
    return re.sub(r"(?<!\\)\|", r"\\|", text)


def row(*cells: str) -> str:
    return "| " + " | ".join(cell(text) for text in cells) + " |"


def listing(names: list[str]) -> str:
    """`a`, `a and b`, `a, b and c`."""
    if len(names) <= 1:
        return "".join(names)
    return ", ".join(names[:-1]) + " and " + names[-1]


NUMBERS = (
    "no",
    "one",
    "two",
    "three",
    "four",
    "five",
    "six",
    "seven",
    "eight",
    "nine",
    "ten",
    "eleven",
    "twelve",
)


def number(count: int, capital: bool = False) -> str:
    """A count as prose writes it: words up to twelve, digits above."""
    word = NUMBERS[count] if count < len(NUMBERS) else str(count)
    return word[:1].upper() + word[1:] if capital else word


def spelled(python: list[str]) -> str:
    return listing([f"`{name}`" for name in python])


def wrap(text: str, width: int = 79, hanging: str = "") -> list[str]:
    """Break one generated paragraph the way the prose around it breaks.

    Every line after the first opens with @p hanging, which is how a list
    item's continuation stays inside the item.
    """
    lines: list[str] = []
    current = ""
    for word in text.split(" "):
        if current.strip() and len(current) + 1 + len(word) > width:
            lines.append(current)
            current = hanging + word
        else:
            current = f"{current} {word}" if current.strip() else current + word
    lines.append(current)
    return lines


class Writer:
    def __init__(self, ledger: Ledger, prose: dict[str, str]) -> None:
        self.ledger = ledger
        self.prose = prose
        self.lines: list[str] = []

    def emit(self, *lines: str) -> None:
        self.lines.extend(lines)

    def paragraph(self, text: str) -> None:
        self.emit(*wrap(text), "")

    def block(self, name: str) -> None:
        self.emit(f"<!-- prose: {name} -->")
        text = self.prose.get(name, "")
        if text:
            self.emit(*text.split("\n"))
        self.emit(PROSE_CLOSE, "")

    def document(self) -> str:
        self.emit(HEADER, "", "# Python authoring coverage", "")
        self.block("introduction")
        self.status()
        self.library_coverage()
        self.python_studies()
        self.catalog_audit()
        self.emit("## Translating a C++ source", "")
        self.block("translating")
        self.emit("## Verification", "")
        self.block("verification")
        while self.lines and self.lines[-1] == "":
            self.lines.pop()
        return "\n".join(self.lines) + "\n"

    # -- Status ------------------------------------------------------------

    def status(self) -> None:
        ledger = self.ledger
        self.emit("## Status", "")
        self.paragraph(
            "A sketch counts as bound when every requirement the catalog audit "
            "records for it resolves to its Python spelling in the built "
            "extension. A sketch nobody has audited counts as unbound. The "
            "Python study column counts the bundled studies that port or adapt "
            "a sketch in that collection."
        )
        self.block("status")
        self.emit(
            "| Collection | Sketches | Every requirement bound | Python study |",
            "| --- | ---: | ---: | ---: |",
        )
        totals = [0, 0, 0]
        complete = []
        for collection in ledger.collections:
            sketches = ledger.in_collection(collection)
            counts = [
                len(sketches),
                sum(sketch.bound for sketch in sketches),
                sum(sketch.study is not None for sketch in sketches),
            ]
            totals = [total + count for total, count in zip(totals, counts)]
            if counts[0] == counts[1]:
                complete.append(collection)
            self.emit(row(collection, *(str(count) for count in counts)))
        self.emit(row("**All**", *(f"**{total}**" for total in totals)), "")
        if complete:
            self.paragraph(f"Every sketch in {listing(complete)} is bound.")
        self.one_surface_away()
        self.widely_needed()
        self.unjudged()

    def one_surface_away(self) -> None:
        waiting: dict[str, list[str]] = {}
        natives: dict[str, str] = {}
        for sketch in self.ledger.sketches:
            if sketch.needs is not None and len(sketch.unbound) == 1:
                requirement = sketch.unbound[0]
                waiting.setdefault(requirement.key, []).append(f"`{sketch.name}`")
                natives[requirement.key] = requirement.native
        if not waiting:
            return
        self.paragraph(
            "One surface alone stands between each of these sketches and a translation:"
        )
        for key in sorted(waiting, key=lambda key: (-len(waiting[key]), natives[key])):
            self.emit(
                *wrap(f"- {natives[key]}: {listing(waiting[key])}.", hanging="  ")
            )
        self.emit("")

    def widely_needed(self) -> None:
        counts: dict[str, int] = {}
        for sketch in self.ledger.sketches:
            for requirement in sketch.unbound:
                counts[requirement.key] = counts.get(requirement.key, 0) + 1
        wide = [key for key, count in counts.items() if count >= WIDELY_NEEDED]
        if not wide:
            return
        requirements = self.ledger.requirements
        self.paragraph(
            "These surfaces stand between the most sketches and a translation. "
            f"Each is needed by {number(WIDELY_NEEDED)} or more; the catalog audit names "
            "every surface each sketch needs."
        )
        self.emit("| Not yet bound | Library | Sketches |", "| --- | --- | ---: |")
        for key in sorted(
            wide, key=lambda key: (-counts[key], requirements[key].native)
        ):
            requirement = requirements[key]
            self.emit(row(requirement.native, requirement.library, str(counts[key])))
        self.emit("")

    def unjudged(self) -> None:
        requirements = [
            requirement
            for requirement in self.ledger.requirements.values()
            if requirement.no_python_spelling
        ]
        if not requirements:
            return
        self.paragraph(
            "No Python name can stand for these surfaces, so the extension cannot "
            "judge them and every sketch that needs one counts as unbound. Each is "
            "a claim the audit makes, with its reason:"
        )
        for requirement in sorted(requirements, key=lambda item: item.native):
            needing = sum(
                any(item.key == requirement.key for item in sketch.requires)
                for sketch in self.ledger.sketches
            )
            self.emit(
                *wrap(
                    f"- {requirement.native}, needed by {number(needing)} "
                    f"{'sketch' if needing == 1 else 'sketches'}. "
                    f"{requirement.no_python_spelling}.",
                    hanging="  ",
                )
            )
        self.emit("")

    # -- Library coverage --------------------------------------------------

    def library_coverage(self) -> None:
        extension = self.ledger.extension
        self.emit("## Library coverage", "")
        self.paragraph(
            "Each row states what a Python author can reach today and what the "
            "native library has that Python cannot yet reach. Names under Bound "
            "are spelled as Python reaches them, and each resolves in the built "
            "extension; names under Not yet bound are native C++ spellings."
        )
        silent = extension.silent_modules()
        if silent:
            self.paragraph(
                "These public modules are registered and export nothing yet: "
                + listing([f"`{module}`" for module in silent])
                + "."
            )
        for section in self.ledger.coverage.get("section", []):
            self.emit(f"### {section['title']}", "")
            self.emit("| Surface | Bound | Not yet bound |", "| --- | --- | --- |")
            for entry in section.get("surface", []):
                bound, unbound = self.split(entry)
                self.emit(
                    row(
                        entry["name"],
                        "; ".join(bound) or "Nothing",
                        "; ".join(unbound) or "Nothing",
                    )
                )
            self.emit("")
            self.block(section["prose"])
        self.unbound_libraries()

    def split(self, entry: dict) -> tuple[list[str], list[str]]:
        extension = self.ledger.extension
        bound: list[str] = []
        unbound: list[str] = []
        for item in entry.get("item", []):
            python = list(item.get("python", []))
            if "bound" in item:
                missing = [name for name in python if not extension.resolves(name)]
                if missing:
                    raise LedgerError(
                        f"The {entry['name']} row claims {item['bound']!r} is bound, "
                        f"and the extension has no {spelled(missing)}. Correct "
                        "the item in typing/ledger/coverage.toml."
                    )
                bound.append(item["bound"])
            elif python and extension.all_resolve(python):
                bound.append(item.get("bound_text") or spelled(python))
            else:
                unbound.append(item["native"])
        return bound, unbound

    def unbound_libraries(self) -> None:
        extension = self.ledger.extension
        rows = []
        for label, record in self.ledger.coverage.get("library", {}).items():
            modules = [
                f"{surface.PUBLIC_ROOT}.{module}" for module in record["modules"]
            ]
            if any(
                getattr(importlib.import_module(module), "__all__", [])
                for module in modules
                if extension.resolves(module.removeprefix(surface.PUBLIC_ROOT + "."))
            ):
                continue
            needed = [
                requirement
                for requirement in self.ledger.requirements.values()
                if requirement.library == label
            ]
            names = {requirement.key for requirement in needed}
            sketches = [
                f"`{sketch.name}`"
                for sketch in self.ledger.sketches
                if any(requirement.key in names for requirement in sketch.requires)
            ]
            surfaces = "; ".join(sorted(requirement.native for requirement in needed))
            rows.append(
                row(record["native"], surfaces or "—", ", ".join(sketches) or "—")
            )
        if not rows:
            return
        self.emit("### Libraries without bindings", "")
        self.paragraph("No Python module exports anything from these libraries.")
        self.block("unbound-libraries")
        self.emit("| Library | Native surface the catalog uses | Sketches |")
        self.emit("| --- | --- | --- |", *rows, "")

    # -- Studies -----------------------------------------------------------

    def python_studies(self) -> None:
        studies = self.ledger.studies
        ports = sum(study.relation == "Port" for study in studies)
        adapts = sum(study.relation == "Adaptation" for study in studies)
        self.emit("## Python studies", "")
        self.paragraph(
            f"The {number(len(studies))} bundled Python sketches are authoring studies. "
            f"{number(ports, capital=True)} port a native sketch, {number(adapts)} adapt one, "
            "and the rest "
            "exercise the Python surface without a native counterpart."
        )
        self.block("studies")
        self.emit("| Study | What it combines | Native sketch |", "| --- | --- | --- |")
        for study in studies:
            native = "—"
            if study.relation:
                verb = "Ports" if study.relation == "Port" else "Adapts"
                native = f"{verb} `{study.native}`"
            self.emit(
                row(f"`{study.stem}`", study.combines or "Not yet described", native)
            )
        self.emit("")
        self.block("studies-after")

    # -- Catalog audit -----------------------------------------------------

    def catalog_audit(self) -> None:
        self.emit("## Catalog audit", "")
        self.paragraph(
            "Every registered C++ sketch appears once, under its collection. "
            "**Needs** summarizes the native capabilities its source uses beyond "
            "basic pen verbs. **Not yet bound** names each native surface a "
            "translation still needs, in native spelling; a dash means every "
            "requirement is bound. The sketch's own model, arithmetic and data "
            "become Python code and are not listed."
        )
        groups: dict[str, list[str]] = {}
        for collection in self.ledger.collections:
            groups.setdefault(collection.split(" · ")[0], []).append(collection)
        for group, collections in groups.items():
            nested = len(collections) > 1
            if nested:
                self.emit(f"### {group}", "")
            for collection in collections:
                self.emit(f"{'####' if nested else '###'} {collection}", "")
                self.audit_table(self.ledger.in_collection(collection))

    def audit_table(self, sketches: list[Sketch]) -> None:
        with_study = any(sketch.study for sketch in sketches)
        header = ["Sketch", "Needs", "Not yet bound"] + (
            ["Python study"] if with_study else []
        )
        self.emit("| " + " | ".join(header) + " |", "|" + " --- |" * len(header))
        for sketch in sketches:
            unbound = "; ".join(requirement.native for requirement in sketch.unbound)
            cells = [
                f"`{sketch.name}`",
                sketch.needs if sketch.needs is not None else "Not yet audited",
                (unbound or "—") if sketch.needs is not None else "Not yet audited",
            ]
            if with_study:
                cells.append(self.study_cell(sketch))
            self.emit(row(*cells))
        self.emit("")

    @staticmethod
    def study_cell(sketch: Sketch) -> str:
        if not sketch.study:
            return ""
        relation, stem = sketch.study
        return f"{relation}: [`{stem}.py`]({STUDY_LINK}/{stem}.py)"


