REGISTRATION = re.compile(r"\bSIGIL_SKETCH(_AS)?\s*\(")
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


@dataclasses.dataclass(frozen=True)
class Registration:
    name: str
    collection: str


def macro_arguments(text: str, start: int) -> list[str]:
    """Split one macro call's arguments at its top-level commas."""
    arguments: list[str] = []
    current = ""
    depth = 0
    quoted = False
    index = start
    while index < len(text):
        character = text[index]
        current += character
        if quoted:
            if character == "\\":
                current += text[index + 1]
                index += 1
            elif character == '"':
                quoted = False
        elif character == '"':
            quoted = True
        elif character == "(":
            depth += 1
        elif character == ")":
            if depth == 0:
                arguments.append(current[:-1].strip())
                return arguments
            depth -= 1
        elif character == "," and depth == 0:
            arguments.append(current[:-1].strip())
            current = ""
        index += 1
    raise LedgerError("a sketch registration never closes its parentheses")


def literal(argument: str) -> str | None:
    """The string an argument of adjacent literals spells, or None for nullptr."""
    if argument == "nullptr":
        return None
    return "".join(LITERAL.findall(argument))


def registrations(root: pathlib.Path) -> dict[str, Registration]:
    """Every C++ sketch the directory registers, by the name it files under.

    A sketch files under its own name when SIGIL_SKETCH_AS gives one and
    under its stem otherwise: the file's, or its directory's when the
    sketch is a directory.
    """
    found: dict[str, Registration] = {}
    for path in sorted(root.rglob("*")):
        if path.suffix not in {".cpp", ".mm", ".h"}:
            continue
        # A hidden directory is a tool's, an interpreter environment above all.
        if any(part.startswith(".") for part in path.relative_to(root).parts):
            continue
        text = path.read_text(errors="replace")
        for match in REGISTRATION.finditer(text):
            opening = text.rfind("\n", 0, match.start()) + 1
            if text[opening : match.start()].strip().startswith(("//", "*", "#")):
                continue
            arguments = macro_arguments(text, match.end())
            relative = path.relative_to(root)
            stem = relative.parts[0] if len(relative.parts) > 1 else path.stem
            if match.group(1):
                name = literal(arguments[1]) or stem
                collection = literal(arguments[2]) or ""
            else:
                name, collection = stem, literal(arguments[1]) or ""
            found[name] = Registration(name, collection)
    return found


def studies(root: pathlib.Path) -> list[str]:
    return sorted(path.stem for path in root.glob("python_*.py"))


