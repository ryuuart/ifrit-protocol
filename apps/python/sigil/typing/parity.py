def read_prose(text: str) -> dict[str, str]:
    """The prose blocks an author wrote, by name, exactly as written."""
    blocks: dict[str, str] = {}
    name: str | None = None
    body: list[str] = []
    for number, line in enumerate(text.splitlines(), start=1):
        opening = PROSE_OPEN.match(line)
        if opening:
            if name is not None:
                raise LedgerError(
                    f"PARITY.md:{number}: a prose block opens inside {name}"
                )
            name, body = opening.group(1), []
        elif line == PROSE_CLOSE:
            if name is None:
                raise LedgerError(
                    f"PARITY.md:{number}: a prose block closes that never opened"
                )
            if name not in PROSE:
                raise LedgerError(
                    f"PARITY.md:{number}: the prose block `{name}` has no place in "
                    f"the ledger; its places are {', '.join(PROSE)}"
                )
            blocks[name] = "\n".join(body)
            name = None
        elif name is not None:
            if line.lstrip().startswith("|"):
                raise LedgerError(
                    f"PARITY.md:{number}: the prose block `{name}` holds a table "
                    "row; the ledger's tables are generated, so state the fact "
                    "in typing/ledger instead"
                )
            body.append(line)
    if name is not None:
        raise LedgerError(f"PARITY.md: the prose block {name} never closes")
    return blocks


def first_difference(old: str, new: str) -> str:
    old_lines = old.splitlines()
    new_lines = new.splitlines()
    for number, (was, wants) in enumerate(zip(old_lines, new_lines), start=1):
        if was != wants:
            return (
                f"PARITY.md:{number} disagrees with the extension and typing/ledger.\n"
                f"  checked in: {was}\n  generated:  {wants}"
            )
    number = min(len(old_lines), len(new_lines)) + 1
    return f"PARITY.md:{number}: the checked-in ledger and the generated one differ in length."


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit non-zero at the first line PARITY.md disagrees on",
    )
    parser.add_argument(
        "--sketches",
        type=pathlib.Path,
        default=SKETCHES,
        help="the directory the C++ sketches and Python studies are registered in",
    )
    parser.add_argument(
        "--diff",
        action="store_true",
        help="with --check, print the whole difference rather than its first line",
    )
    args = parser.parse_args()

    from generate import extension_under_pythonpath

    extension_under_pythonpath()
    # The package's own modules as the checkout holds them, over the
    # extension PYTHONPATH names: the modules generate.py has just
    # refreshed, not the copy a build staged beside the extension.
    sys.path.insert(0, str(PROJECT))
    absent = absent_optional_modules()
    if absent:
        # The ledger describes a build with every optional SDK, so one
        # without them cannot say what it should read.
        print(
            "typing/parity.py: SKIPPED: this extension was built without "
            f"{', '.join(absent)}, so it cannot judge PARITY.md, and "
            + ("nothing was checked." if args.check else "PARITY.md was not written."),
            file=sys.stderr,
        )
        return SKIPPED
    old = TARGET.read_text() if TARGET.is_file() else ""
    try:
        new = Writer(Ledger(Extension(), args.sketches), read_prose(old)).document()
    except LedgerError as error:
        print(f"typing/parity.py: {error}", file=sys.stderr)
        return 1
    if args.check:
        if old == new:
            return 0
        print(first_difference(old, new), file=sys.stderr)
        if args.diff:
            sys.stderr.writelines(
                difflib.unified_diff(
                    old.splitlines(keepends=True),
                    new.splitlines(keepends=True),
                    "checked-in/PARITY.md",
                    "generated/PARITY.md",
                )
            )
        print(
            "Regenerate it with typing/parity.py and commit the result.",
            file=sys.stderr,
        )
        return 1
    if old != new:
        TARGET.write_text(new)
        print(f"Wrote {TARGET}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
