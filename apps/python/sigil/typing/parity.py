class Extension:
    """Answers whether a Python spelling resolves in the built extension."""

    def __init__(self) -> None:
        self._known: dict[str, bool] = {}

    def resolves(self, spelling: str) -> bool:
        if spelling not in self._known:
            self._known[spelling] = self._resolve(spelling)
        return self._known[spelling]

    def all_resolve(self, spellings: Iterable[str]) -> bool:
        return all(self.resolves(spelling) for spelling in spellings)

    def _resolve(self, spelling: str) -> bool:
        match = re.fullmatch(r"([\w.]+)(?:\((.*)\))?", spelling)
        if not match:
            raise LedgerError(f"`{spelling}` is not a dotted Python spelling")
        found = self._lookup(f"{surface.PUBLIC_ROOT}.{match.group(1)}")
        if found is None:
            return False
        if match.group(2) is None:
            return True
        wanted = [name.strip() for name in match.group(2).split(",") if name.strip()]
        return any(
            parameters[: len(wanted)] == wanted
            for parameters in overload_parameters(found)
        )

    @staticmethod
    def _lookup(dotted: str) -> object | None:
        parts = dotted.split(".")
        for size in range(len(parts), 0, -1):
            try:
                found: object = importlib.import_module(".".join(parts[:size]))
            except ImportError:
                continue
            for part in parts[size:]:
                found = getattr(found, part, None)
                if found is None:
                    return None
            return found
        return None

    def silent_modules(self) -> list[str]:
        """The public modules with no children that export no name yet."""
        silent = []
        for public in sorted(set(surface.PUBLIC_MODULES.values())):
            raws = surface.raw_modules(public)
            if (
                surface.child_modules(public)
                or any(raw in surface.DECLARATION_ONLY for raw in raws)
                or any(raw in surface.OPTIONAL_MODULES for raw in raws)
            ):
                continue
            module = importlib.import_module(public)
            if not list(getattr(module, "__all__", [])):
                silent.append(public)
        return silent


def overload_parameters(value: object) -> list[list[str]]:
    """The parameter names of each signature a bound callable documents."""
    signatures = []
    for line in (getattr(value, "__doc__", None) or "").splitlines():
        match = re.match(r"^\s*(?:\d+\.\s*)?\w+\((.*)\)\s*->", line)
        if not match:
            continue
        names = []
        depth = 0
        current = ""
        for character in match.group(1) + ",":
            if character in "[(":
                depth += 1
            elif character in "])":
                depth -= 1
            if character == "," and depth == 0:
                name = current.split(":")[0].split("=")[0].strip().lstrip("*")
                if name and name != "self":
                    names.append(name)
                current = ""
            else:
                current += character
        signatures.append(names)
    return signatures


def absent_optional_modules() -> list[str]:
    """The licensed-SDK modules this extension was built without."""
    absent = []
    for raw in sorted(surface.OPTIONAL_MODULES):
        try:
            importlib.import_module(raw)
        except ModuleNotFoundError:
            absent.append(raw)
    return absent


