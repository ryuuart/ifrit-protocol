def build():
    builder = FontBuilder(1000, isTTF=True)
    names = [".notdef"] + [f"uni{ord(c):04X}" for c in STROKES]
    builder.setupGlyphOrder(names)
    glyphs, metrics = {}, {}
    for character, runs in {"\0": [], **STROKES}.items():
        name = ".notdef" if character == "\0" else f"uni{ord(character):04X}"
        p = TTGlyphPen(None)
        width = 50
        for run in runs:
            for (ax, ay), (bx, by) in pairwise(run):
                distance = hypot(bx - ax, by - ay)
                nx, ny = (
                    -(by - ay) / distance * width / 2,
                    (bx - ax) / distance * width / 2,
                )
                p.moveTo((round(ax + nx + 65), round(ay + ny)))
                for x, y in (
                    (bx + nx, by + ny),
                    (bx - nx, by - ny),
                    (ax - nx, ay - ny),
                ):
                    p.lineTo((round(x + 65), round(y)))
                p.closePath()
        glyphs[name] = p.glyph()
        metrics[name] = (680, 40)
    builder.setupCharacterMap({ord(c): f"uni{ord(c):04X}" for c in STROKES})
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics(metrics)
    builder.setupHorizontalHeader(ascent=760, descent=-240)
    builder.setupNameTable(
        {
            "familyName": "Muthur Study",
            "styleName": "Regular",
            "uniqueFontIdentifier": "MuthurStudy-OriginalVector",
            "fullName": "Muthur Study Regular",
            "psName": "MuthurStudy-Regular",
        }
    )
    builder.setupOS2(
        sTypoAscender=760, sTypoDescender=-240, usWinAscent=800, usWinDescent=240
    )
    builder.setupPost(isFixedPitch=1)
    builder.setupMaxp()
    builder.save(Path(__file__).with_name("MachineType.ttf"))


if __name__ == "__main__":
    build()
